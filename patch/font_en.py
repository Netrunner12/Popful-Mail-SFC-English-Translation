def logo_cells():
    """-> (left, right) 8x16 cells with outline, logo occupying x=1..14 of the 16-px pair"""
    W = 16; c = [[0]*W for _ in range(16)]
    for y, r in enumerate(LOGO):
        for x, p in enumerate(r):
            if p == '#': c[y+1][x+1] = 2
    for y in range(16):
        for x in range(W):
            if c[y][x] == 0 and any(0 <= y+dy < 16 and 0 <= x+dx < W and c[y+dy][x+dx] == 2
                                    for dy in (-1,0,1) for dx in (-1,0,1)):
                c[y][x] = 1
    return [row[:8] for row in c], [row[8:] for row in c]
