def cell(ch):
    """8x16 cell, values 0/1/2 (1 = outline, 2 = stroke), body at x=1..5, rows 2..10"""
    rows = G[ch]; c = [[0]*8 for _ in range(16)]
    for y, r in enumerate(rows):
        for x, p in enumerate(r):
            if p == '#': c[y+2][x+1] = 2
    for y in range(16):
        for x in range(8):
            if c[y][x] == 0 and any(0 <= y+dy < 16 and 0 <= x+dx < 8 and c[y+dy][x+dx] == 2
                                    for dy in (-1,0,1) for dx in (-1,0,1)):
                c[y][x] = 1
    return c

# Blacky's brand mark (a ring with a Z-shaped bolt, as in the original kanji-sized glyph),
# drawn across two 8-px cells: '◐' = left half, '◑' = right half.  14 x 11 pixels.
